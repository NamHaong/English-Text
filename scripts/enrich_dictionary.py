def clean_word(word):
    cleaned = re.sub(r'\d+$', '', word)
    cleaned = re.sub(r'\(.*?\)', '', cleaned).strip()
    return cleaned

def enrich_vocab():
    path = r"D:\APP IOS\English Text\src\data\vocabulary.json"
    with open(path, "r", encoding="utf-8") as f:
        words = json.load(f)

    updated_count = 0
    for item in words:
        w = clean_word(item.get("word", "")).lower()
        if w in EN_VI_MAP:
            meaning, ipa = EN_VI_MAP[w]
            item["meaning"] = meaning
            item["ipa"] = ipa
            updated_count += 1
        elif "meaning" in item and (item["meaning"].startswith("thực hiện hành động") or item["meaning"].startswith("từ ")):
            # If still raw placeholder, clean it nicely
            raw_w = item["word"]
            pos = item.get("pos", "")
            if "n." in pos:
                item["meaning"] = f"danh từ {raw_w}"
            elif "v." in pos:
                item["meaning"] = f"động từ {raw_w}"
            elif "adj." in pos:
                item["meaning"] = f"tính từ {raw_w}"
            else:
                item["meaning"] = f"{raw_w}"

    with open(path, "w", encoding="utf-8") as f:
        json.dump(words, f, ensure_ascii=False, indent=2)

    print(f"Enriched {updated_count} words with precise Vietnamese meanings & IPA.")

if __name__ == "__main__":
    enrich_vocab()
